import {
  BadGatewayException,
  BadRequestException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { randomUUID } from 'crypto';
import { PrismaService } from '../prisma/prisma.service';
import { MinioService } from '../assets/minio.service';
import { ActivityService } from '../activity/activity.service';
import { AudioProvidersService } from './audio-providers.service';
import { GenerateVoiceSampleDto } from './dto/audio-provider.dto';

type MageRequest = {
  request_id: string;
  status: 'queued' | 'in_progress' | 'completed' | 'failed' | 'cancelled';
  status_url: string;
  billing?: { gems_charged?: number; gems_refunded?: number };
  result?: { type: string; url: string } | null;
  error?: { code?: string; message?: string } | null;
};

@Injectable()
export class VoiceSampleService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly minio: MinioService,
    private readonly audioProviders: AudioProvidersService,
    private readonly activity: ActivityService,
  ) {}

  async generate(
    seriesId: string,
    entityId: string,
    userId: string,
    dto: GenerateVoiceSampleDto,
  ) {
    const character = await this.prisma.worldEntity.findFirst({
      where: { id: entityId, seriesId, type: 'CHARACTER' },
    });
    if (!character) throw new NotFoundException('Character not found');
    const voiceProfile = dto.voiceProfile?.trim() || character.voiceProfile?.trim();
    if (!voiceProfile) {
      throw new BadRequestException(
        'Add and save a Voice Profile before generating a voice sample.',
      );
    }

    const provider = await this.audioProviders.getActiveKey(seriesId);
    const phrase = (
      dto.sampleText?.trim() ||
      'Every choice leaves a mark; this is mine.'
    ).replace(/["\r\n]/g, ' ');
    const prompt = [
      'Generate a clean voice-profile reference sample with one speaker only.',
      `Character: ${character.displayName}.`,
      `Voice identity: ${voiceProfile}.`,
      character.voiceDescription
        ? `Additional delivery notes: ${character.voiceDescription.trim()}.`
        : '',
      `Speak exactly this line: "${phrase}"`,
      'Dry studio-quality voice, natural delivery, no music, no sound effects, no ambience, no second speaker.',
    ]
      .filter(Boolean)
      .join(' ')
      .slice(0, 2986);

    const submitted = await this.mageFetch<MageRequest>(
      `${provider.baseUrl}/v1/seed_audio/generate`,
      provider.apiKey,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Idempotency-Key': `voice-${seriesId}-${entityId}-${randomUUID()}`,
        },
        body: JSON.stringify({
          prompt,
          model_id: 'seed-audio-1.0',
          duration: '5',
          sample_rate: 48000,
          speech_rate: 0,
          loudness_rate: 0,
          pitch_rate: 0,
        }),
      },
    );
    const completed = await this.waitForMage(
      submitted,
      provider.apiKey,
      provider.baseUrl,
    );
    if (
      completed.status !== 'completed' ||
      completed.result?.type !== 'audio' ||
      !completed.result.url
    ) {
      throw new BadGatewayException(
        completed.error?.message ?? `Mage generation ${completed.status}.`,
      );
    }

    const audio = await this.downloadAudio(completed.result.url);
    const filename = `${this.safeFilename(character.displayName)}-voice-sample.mp3`;
    const storageKey = `assets/${seriesId}/generated/${randomUUID()}/${filename}`;
    await this.minio.putObject(storageKey, audio, 'audio/mpeg');

    try {
      const asset = await this.prisma.$transaction(async tx => {
        await tx.asset.updateMany({
          where: {
            seriesId,
            type: 'AUDIO',
            isFinal: true,
            entityLinks: { some: { entityId } },
          },
          data: { isFinal: false },
        });
        const created = await tx.asset.create({
          data: {
            seriesId,
            uploadedById: userId,
            type: 'AUDIO',
            status: 'UPLOADED',
            title: `${character.displayName} — generated voice sample`,
            description:
              'Five-second voice-profile reference generated by Mage Seed Audio.',
            tags: ['voice-sample', 'generated', 'mage', 'seed-audio'],
            filename,
            storageKey,
            mimeType: 'audio/mpeg',
            sizeBytes: BigInt(audio.length),
            versionNotes: `Mage request ${completed.request_id}; ${completed.billing?.gems_charged ?? 'unknown'} gems charged`,
            isFinal: true,
            provenance: {
              create: {
                source: 'MAGE_SEED_AUDIO',
                provider: 'MAGE',
                model: 'seed-audio-1.0',
                requestId: completed.request_id,
                prompt,
                durationSeconds: 5,
              },
            },
            entityLinks: { create: { entityId } },
          },
        });

        // Abandon previous voice sample assignment for this entity
        await tx.assetAssignment.updateMany({
          where: {
            seriesId,
            targetType: 'ENTITY',
            targetId: entityId,
            role: 'VOICE_SAMPLE',
            status: 'ASSIGNED',
          },
          data: {
            status: 'ABANDONED',
            replacedByAssetId: created.id,
            replacementNote: `Replaced by new Mage generation on ${new Date().toISOString()}. New request: ${completed.request_id}.`,
          },
        });

        // Create new assignment
        await tx.assetAssignment.create({
          data: {
            assetId: created.id,
            seriesId,
            targetType: 'ENTITY',
            targetId: entityId,
            role: 'VOICE_SAMPLE',
            status: 'ASSIGNED',
          },
        });

        await tx.worldEntity.update({
          where: { id: entityId },
          data: { voiceSampleAssetId: created.id, voiceProfile },
        });
        return created;
      });
      const downloadUrl = await this.minio.presignedGetUrl(storageKey, 3600);
      await this.activity.log(
        seriesId,
        userId,
        'CHARACTER_VOICE_SAMPLE_GENERATED',
        'WorldEntity',
        entityId,
        `Mage Seed Audio, 5 seconds, request ${completed.request_id}`,
      );
      return {
        assetId: asset.id,
        voiceSampleAssetId: asset.id,
        downloadUrl,
        durationSeconds: 5,
        provider: 'MAGE',
        model: 'seed-audio-1.0',
        mageRequestId: completed.request_id,
        gemsCharged: completed.billing?.gems_charged,
      };
    } catch (error) {
      await this.minio.deleteObject(storageKey).catch(() => undefined);
      throw error;
    }
  }

  private async waitForMage(
    request: MageRequest,
    apiKey: string,
    baseUrl: string,
  ) {
    let current = request;
    let delayMs = 5_000;
    const deadline = Date.now() + 180_000;
    while (current.status === 'queued' || current.status === 'in_progress') {
      if (Date.now() >= deadline) {
        throw new BadGatewayException(
          'Mage voice generation timed out after three minutes.',
        );
      }
      await new Promise(resolve => setTimeout(resolve, delayMs));
      const statusUrl = new URL(current.status_url);
      if (statusUrl.origin !== new URL(baseUrl).origin) {
        throw new BadGatewayException('Mage returned an invalid status URL.');
      }
      current = await this.mageFetch<MageRequest>(
        statusUrl.toString(),
        apiKey,
        { method: 'GET' },
      );
      delayMs = Math.min(Math.round(delayMs * 1.5), 15_000);
    }
    return current;
  }

  private async downloadAudio(url: string) {
    const parsed = new URL(url);
    if (parsed.protocol !== 'https:') {
      throw new BadGatewayException('Mage returned an invalid audio URL.');
    }
    const response = await fetch(parsed, {
      signal: AbortSignal.timeout(60_000),
    });
    if (!response.ok) {
      throw new BadGatewayException(
        `Could not download generated audio (${response.status}).`,
      );
    }
    const announcedSize = Number(response.headers.get('content-length') ?? 0);
    if (announcedSize > 20 * 1024 * 1024) {
      throw new BadGatewayException('Generated audio exceeds the 20 MB limit.');
    }
    const data = Buffer.from(await response.arrayBuffer());
    if (!data.length || data.length > 20 * 1024 * 1024) {
      throw new BadGatewayException('Generated audio has an invalid size.');
    }
    return data;
  }

  private async mageFetch<T>(
    url: string,
    apiKey: string,
    init: RequestInit,
  ): Promise<T> {
    const response = await fetch(url, {
      ...init,
      headers: {
        Authorization: `Bearer ${apiKey}`,
        ...(init.headers ?? {}),
      },
      signal: AbortSignal.timeout(30_000),
    });
    const text = await response.text();
    let body: any = {};
    try {
      body = text ? JSON.parse(text) : {};
    } catch {
      body = { message: text.slice(0, 500) };
    }
    if (!response.ok) {
      throw new BadGatewayException(
        body?.error?.message ??
          body?.message ??
          `Mage request failed (${response.status}).`,
      );
    }
    return body as T;
  }

  private safeFilename(value: string) {
    return (
      value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '') || 'character'
    );
  }
}
